import assert from 'node:assert/strict'
import { criarRascunhosDeNotas } from '../src/aplicacao/rascunhosDeNotas.js'

const notas = criarRascunhosDeNotas('empresa:atendente')
const marina = notas.abrir('marina', 'Marina', 'Retirar depois das 18h')
notas.guardar(marina.chave, { texto: 'Retirar depois das 18h, sem molho.', inicio: 8, fim: 14, rolagem: 76 })
notas.pausar()
assert.equal(notas.ler().ativa, null)
const carlos = notas.abrir('carlos', 'Carlos', 'Sem queijo')
assert.notEqual(carlos.chave, marina.chave)
assert.equal(notas.abrir('marina', 'Marina', 'Não substituir').texto, 'Retirar depois das 18h, sem molho.')
assert.deepEqual([marina.inicio, marina.fim, marina.rolagem], [8, 14, 76])

// A resposta da API de Marina pode chegar enquanto Carlos está sendo escrito.
notas.abrir('carlos', 'Carlos')
assert.equal(notas.iniciarGravacao(marina.chave), true)
assert.equal(notas.iniciarGravacao(marina.chave), false, 'dois envios não repetem a mesma gravação')
notas.falharGravacao(marina.chave, 'Sem confirmação')
assert.equal(marina.erro, 'Sem confirmação')
assert.equal(marina.gravando, false)
assert.equal(notas.concluir(marina.chave, false), false)
assert.equal(notas.ler().rascunhos.length, 2, 'falha não descarta texto')
assert.equal(notas.concluir(marina.chave, undefined), false, 'sem confirmação não conclui')
assert.equal(notas.concluir(marina.chave, true), true)
assert.equal(notas.ler().ativa, carlos.chave, 'gravação antiga não fecha outro editor')
assert.equal(notas.ler().rascunhos[0].texto, 'Sem queijo')
const novaMarina = notas.abrir('marina', 'Marina', 'Outra nota')
assert.notEqual(novaMarina.chave, marina.chave, 'novo rascunho tem dono de gravação distinto')
assert.equal(notas.concluir(marina.chave, true), false, 'resposta repetida não apaga a nota seguinte')
const outraIdentidade = criarRascunhosDeNotas('outra-empresa:atendente')
assert.equal(outraIdentidade.ler().rascunhos.length, 0)
assert.equal(outraIdentidade.concluir(novaMarina.chave, true), false)
assert.equal(notas.ler().rascunhos.length, 2)
console.log('ok #2178: rascunhos privados por identidade/conversa, posição preservada e confirmação limitada ao proprietário')
