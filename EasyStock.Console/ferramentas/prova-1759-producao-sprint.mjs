/* eslint-disable no-console */
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const origem = process.env.CONSOLE_URL ?? 'http://127.0.0.1:5771'
const dir = process.env.EVIDENCIAS_UX ?? new URL('../../.build/1759/depois-final/', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')
mkdirSync(dir, { recursive: true })
const nomes = ['Talharim', 'Lasanha de carne', 'Nhoque de batata', 'Ravioli de ricota', 'Capeletti', 'Rondelli', 'Canelone', 'Molho sugo', 'Molho branco', 'Molho bolonhesa', 'Almôndegas', 'Quiche', 'Torta de frango', 'Panqueca', 'Escondidinho', 'Frango assado']
const itens = nomes.map((nome, i) => ({ id: `i-${i+1}`, nome, pesoExibicao: '500 g', precoCentavos: 3000, categoria: i < 7 ? 'Massas' : 'Pratos', linha: 'paraServir', disponivel: true, estoqueAtual: i ? 4 : 0 }))
const registros = []
const browser = await chromium.launch({ headless: true })
async function consoleTeste(width) {
  const context = await browser.newContext({ viewport: { width, height: 844 }, reducedMotion: 'reduce' })
  await context.addInitScript(() => sessionStorage.setItem('easystok.sessao', JSON.stringify({ token: 'controle-local', expiraEm: Date.now()+3600000, empresa: { id: '11111111-1111-4111-8111-111111111111', nome: 'Cozinha de teste' }, usuario: { id: '22222222-2222-4222-8222-222222222222', nome: 'Dona de teste' } })))
  let envios = [], erros = [], modo = 'ok', responder
  await context.route(url => url.pathname.startsWith('/api/'), async route => {
    const r = route.request(), path = new URL(r.url()).pathname
    const ok = data => route.fulfill({ json: { data } })
    if (path === '/api/auth/me/modulos') return ok({ modulos: ['producao', 'atendimento', 'cozinha', 'cardapio'].map(id => ({ id, liberado: true })), acoes: { editarProducao: true, editarCardapio: true } })
    if (path === '/api/atendimento/comanda/cardapio') return ok({ itens, porcoes: {} })
    if (path.endsWith('/estoque-do-dia')) return ok({ pratos: itens.map(p => ({ cardapioItemId: p.id, nome: p.nome, saldo: p.estoqueAtual, fisico: p.estoqueAtual, descoberto: 0, lotes: [], porcoes: [] })), alertas: [] })
    if (path.endsWith('/producao/sugestao')) return ok({ ate: '2026-10-14', pratos: [{ cardapioItemId: 'i-1', produtoId: 'p-1', nome: 'Talharim', minimo: 2, saldo: 0, agendados: 2, descoberto: 0, sugestao: 4 }] })
    if (path === '/api/atendimento/producao' && r.method() === 'POST') {
      envios.push({ body: r.postDataJSON(), key: r.headers()['idempotency-key'] })
      if (modo === 'sem-resposta') return route.abort('failed')
      if (modo === 'pendente') await new Promise(resolve => { responder = resolve })
      return ok({ loteId: 'l-1', codigoLote: 'LOT-TESTE-001', totalEtiquetas: 2, pratos: [{ cardapioItemId: 'i-1', nome: 'Talharim', porcoes: 2, sobraG: null }], avisos: [] })
    }
    if (path.endsWith('/etiquetas/render')) return ok({ etiquetas: [{ id: 'et-1', sequencial: 1, produto: { nome: 'Talharim', pesoG: 500, fichaAlergenos: [] }, loteCodigo: 'LOT-TESTE-001', loteCriadoEm: '2026-10-13T12:00:00Z', loteValidadeEm: '2026-10-18T12:00:00Z', codigo: 'ET-1' }] })
    if (r.method() !== 'GET') return route.fulfill({ status: 400, json: { error: { message: 'Escrita inesperada' } } })
    if (/nao-lidas|count/.test(path)) return ok({ total: 0 })
    if (path.endsWith('/configuracao')) return ok({})
    return ok([])
  })
  const page = await context.newPage()
  page.on('pageerror', err => erros.push(err.message))
  await page.goto(origem + '/#/m/producao/producao')
  const prato = page.getByRole('button', { name: 'Somar 1 porção de Talharim 500 g', exact: true })
  await prato.waitFor()
  await page.screenshot({ path: join(dir, `console-${width}-01-inicial.png`) })
  await prato.click(); await prato.click()
  await page.screenshot({ path: join(dir, `console-${width}-02-selecao.png`) })
  const medidas = await page.evaluate(() => { const form = document.querySelector('#lote-da-producao'); return { loteTop: form?.getBoundingClientRect().top ?? null, altura: innerHeight, larguraPagina: document.documentElement.scrollWidth, largura: innerWidth } })
  const conferir = page.getByRole('button', { name: 'Conferir produção', exact: true })
  const revisao = page.getByRole('dialog', { name:'Conferir produção', exact:true })
  await conferir.click()
  assert.equal(envios.length, 0, 'abrir revisão não grava')
  const posicaoRevisao = await revisao.boundingBox()
  assert.ok(posicaoRevisao.y >= 0 && posicaoRevisao.y < 844)
  await page.screenshot({ path: join(dir, `console-${width}-03-revisao.png`) })
  const form = page.locator('#lote-da-producao')
  await form.locator('summary').first().click()
  await form.getByLabel('Validade em dias de Talharim 500 g', { exact: true }).fill('7')
  await page.screenshot({ path: join(dir, `console-${width}-04-ajuste.png`) })
  const botao = page.getByRole('button', { name: 'Confirmar produção', exact: true }).filter({ visible: true })
  await botao.click()
  await page.getByRole('button', { name: 'Imprimir 2 etiquetas do lote LOT-TESTE-001', exact: true }).waitFor()
  await page.screenshot({ path: join(dir, `console-${width}-05-confirmado.png`) })
  assert.equal(envios.length, 1); assert.equal(envios[0].body.pratos[0].validadeDias, 7)
  assert.equal(envios[0].body.pratos[0].porcoes, 2); assert.equal(envios[0].body.pratos[0].pesoPorPorcaoG, 500)
  await page.evaluate(() => { window.__impressoes = 0; window.print = () => { window.__impressoes += 1 } })
  await page.getByRole('button', { name: 'Imprimir 2 etiquetas do lote LOT-TESTE-001', exact: true }).click()
  await page.waitForFunction(() => window.__impressoes === 1)
  await prato.click(); await prato.click(); await conferir.click()
  await page.keyboard.press('Escape')
  await revisao.waitFor({ state:'hidden' })
  assert.equal(await conferir.evaluate(el => el === document.activeElement), true, 'Esc devolve foco à revisão')
  await conferir.click()
  await form.locator('summary').first().click()
  const validade = form.getByLabel('Validade em dias de Talharim 500 g', { exact:true })
  await validade.fill('0')
  await revisao.getByRole('button', { name:'Confirmar produção', exact:true }).click()
  await revisao.getByRole('alert').waitFor()
  assert.equal(await validade.evaluate(el => el === document.activeElement), true)
  assert.equal(await validade.getAttribute('aria-invalid'), 'true')
  assert.equal(envios.length, 1)
  // Mesmo erro repetido não perde nem confirma o lote.
  await revisao.getByRole('button', { name:'Confirmar produção', exact:true }).click()
  assert.equal(await validade.inputValue(), '0')
  assert.equal(await validade.evaluate(el => el === document.activeElement), true, 'erro repetido volta ao campo inválido')
  await page.screenshot({ path: join(dir, `console-${width}-06-invalido.png`) })
  await validade.fill('7')
  await revisao.getByRole('button', { name:'Voltar aos pratos', exact:true }).click()
  await conferir.click(); await form.locator('summary').first().click()
  assert.equal(await validade.inputValue(), '7')
  assert.equal(await form.getByLabel('Porções de Talharim 500 g', { exact:true }).inputValue(), '2')
  modo = 'sem-resposta'
  await revisao.getByRole('button', { name:'Confirmar produção', exact:true }).click()
  await revisao.getByRole('alert').filter({ hasText:'Sem conexão' }).waitFor()
  assert.equal(await validade.inputValue(), '7')
  assert.equal(await form.getByLabel('Porções de Talharim 500 g', { exact:true }).inputValue(), '2')
  await page.screenshot({ path: join(dir, `console-${width}-07-sem-resposta.png`) })
  modo = 'pendente'
  await revisao.getByRole('button', { name:'Confirmar produção', exact:true }).click()
  await page.waitForFunction(() => document.querySelector('dialog[open] button[form]')?.disabled)
  assert.equal(await revisao.getByRole('button', { name:'Fechar janela', exact:true }).isDisabled(), true)
  await page.keyboard.press('Escape')
  assert.equal(await revisao.isVisible(), true)
  await page.screenshot({ path: join(dir, `console-${width}-08-enviando.png`) })
  for (let n=0; n<40 && !responder; n+=1) await page.waitForTimeout(25)
  assert.equal(typeof responder, 'function'); responder()
  await revisao.waitFor({ state:'hidden' })
  assert.equal(envios.length, 3)
  assert.ok(envios[1].key)
  assert.equal(envios[1].key, envios[2].key, 'retomada do mesmo lote mantém chave')
  assert.deepEqual(envios[1].body, envios[2].body)
  assert.ok(await page.getByRole('button', { name:'Imprimir 2 etiquetas do lote LOT-TESTE-001', exact:true }).isVisible())
  await page.screenshot({ path: join(dir, `console-${width}-09-retomada.png`) })
  assert.deepEqual(erros, [])
  registros.push({ app: 'Console', width, medidas, posicaoRevisao, envios, erros, cenario:'seleção, revisão, ajuste, registro, impressão, Esc/foco, erro repetido, volta, perda de resposta, retomada com mesma chave e envio travado' })
  await context.close()
}
try { for (const width of [1280,390]) await consoleTeste(width) }
finally { writeFileSync(join(dir,'resultado.json'),JSON.stringify(registros,null,2)); await browser.close() }
console.log(JSON.stringify({ viewports:registros.map(r => r.width), cenarios:registros.length, prints:registros.length * 9, erros:registros.flatMap(r => r.erros), evidencias:dir }))
